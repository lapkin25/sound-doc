export const groups: { title: string; sections: DocSection[] }[] = (() => {
  const order: string[] = [];
  const map = new Map<string, DocSection[]>();
  for (const section of sections) {
    if (!map.has(section.group)) {
      map.set(section.group, []);
      order.push(section.group);
    }
    map.get(section.group)!.push(section);
  }
  return order.map((title) => ({ title, sections: map.get(title)! }));
})();
